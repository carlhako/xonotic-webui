"""The installed-map catalogue, read from the game's and the user's ``.pk3`` packages.

A package is a zip file; only its directory and the small ``.mapinfo`` members are read
(design D6):

* ``maps/<name>.bsp`` makes a map;
* ``maps/<name>.mapinfo`` gives ``title``, ``description``, ``author``, the gametypes
  (``gametype <id>``, or the older ``type <id>``) and ``hidden``;
* ``maps/<name>.jpg`` / ``.png`` is the preview image.

A map in the user directory shadows one of the same name in the game tree; within a
directory a package that sorts later takes precedence. Hidden maps and names starting
with ``_`` (``_hudsetup``) are left out. A map with no ``.mapinfo`` is listed with unknown
gametypes and is not offered for any gametype, until the game has run once: it then writes
a generated map information file for it, which is read instead (see
:data:`GENERATED_DIRS`). The catalogue is rebuilt only when a
package's size or modification time changes.
"""

from __future__ import annotations

import zipfile
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

from xonotic_webui.logging import get_logger

log = get_logger("maps")

# Where the game writes the map information it generates for a map that has none, found
# by running the 0.8.6 server with ``-userdir`` (the doubled ``data`` is real). The second
# is where the design first assumed they would be, kept in case a layout differs.
GENERATED_DIRS = (Path("data/data/maps/autogenerated"), Path("data/maps/autogenerated"))

_IMAGE_TYPES = {".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png"}
_MAX_MAPINFO_BYTES = 64 * 1024
_MAX_PREVIEW_BYTES = 8 * 1024 * 1024


@dataclass(frozen=True)
class MapEntry:
    name: str
    title: str
    description: str
    author: str
    gametypes: tuple[str, ...]  # empty: unknown (no map information)
    has_mapinfo: bool
    preview: bool
    source: str  # "game" or "user"

    def supports(self, gametype: str) -> bool:
        return gametype in self.gametypes


@dataclass(frozen=True)
class _Source:
    path: Path
    origin: str  # "game" | "user"
    priority: int  # higher wins


@dataclass(frozen=True)
class _MapInfo:
    title: str
    description: str
    author: str
    gametypes: tuple[str, ...]
    hidden: bool


def parse_mapinfo(text: str) -> _MapInfo:
    """Parse the lines of a ``.mapinfo`` file; unknown keys are ignored."""
    title = description = author = ""
    gametypes: list[str] = []
    hidden = False
    for raw in text.splitlines():
        line = raw.split("//", 1)[0].strip()
        if not line:
            continue
        key, _, rest = line.partition(" ")
        key = key.lower()
        rest = rest.strip()
        if key == "title":
            title = rest
        elif key == "description":
            description = rest
        elif key == "author":
            author = rest
        elif key in ("gametype", "type"):
            gametype = rest.split(None, 1)[0] if rest else ""
            if gametype and gametype not in gametypes:
                gametypes.append(gametype)
        elif key == "hidden":
            hidden = True
    return _MapInfo(title, description, author, tuple(gametypes), hidden)


class MapCatalogue:
    def __init__(self, game_root: Path, userdir: Path) -> None:
        self._game_data = game_root / "data"
        self._userdir = userdir
        self._user_data = userdir / "data"
        self._signature: tuple | None = None
        self._entries: dict[str, MapEntry] = {}
        # name -> (package path, member name, media type)
        self._previews: dict[str, tuple[Path, str, str]] = {}

    # -- discovery ---------------------------------------------------------------------
    def _sources(self) -> list[_Source]:
        sources: list[_Source] = []
        priority = 0
        # Lowest priority first: the game tree, then the user directory on top.
        for origin, directory in (("game", self._game_data), ("user", self._user_data)):
            try:
                packages = sorted(directory.glob("*.pk3"))
            except OSError:
                packages = []
            for path in packages:
                sources.append(_Source(path, origin, priority))
                priority += 1
        return sources

    def _generated_files(self) -> dict[str, Path]:
        """Generated map information files by map name (the first directory wins)."""
        found: dict[str, Path] = {}
        for rel in GENERATED_DIRS:
            try:
                files = sorted((self._userdir / rel).glob("*.mapinfo"))
            except OSError:
                continue
            for path in files:
                found.setdefault(path.stem, path)
        return found

    def _signature_of(self, sources: list[_Source]) -> tuple:
        sig = []
        for src in sources:
            try:
                st = src.path.stat()
            except OSError:
                continue
            sig.append((str(src.path), st.st_size, st.st_mtime_ns))
        for path in self._generated_files().values():
            try:
                st = path.stat()
            except OSError:
                continue
            sig.append((str(path), st.st_size, st.st_mtime_ns))
        return tuple(sig)

    def _refresh(self) -> None:
        sources = self._sources()
        signature = self._signature_of(sources)
        if signature == self._signature:
            return
        self._build(sources)
        self._signature = signature

    def _build(self, sources: list[_Source]) -> None:
        bsp: dict[str, _Source] = {}
        mapinfo: dict[str, tuple[_Source, str]] = {}
        images: dict[str, tuple[_Source, str, str]] = {}
        for src in sources:  # ascending priority: later assignments win
            try:
                with zipfile.ZipFile(src.path) as zf:
                    names = zf.namelist()
            except (OSError, zipfile.BadZipFile) as exc:
                log.warning("skipping unreadable package %s: %s", src.path, exc)
                continue
            for member in names:
                path = PurePosixPath(member)
                if len(path.parts) != 2 or path.parts[0] != "maps":
                    continue
                stem, suffix = path.stem, path.suffix.lower()
                if suffix == ".bsp":
                    bsp[stem] = src
                elif suffix == ".mapinfo":
                    mapinfo[stem] = (src, member)
                elif suffix in _IMAGE_TYPES:
                    images[stem] = (src, member, _IMAGE_TYPES[suffix])

        generated = self._generated_files()
        entries: dict[str, MapEntry] = {}
        previews: dict[str, tuple[Path, str, str]] = {}
        for name, owner in bsp.items():
            if name.startswith("_"):
                continue
            info: _MapInfo | None = None
            found = mapinfo.get(name)
            if found is not None and found[0].priority >= owner.priority:
                info = self._read_mapinfo(*found)
            elif found is None and name in generated:
                info = self._read_generated(generated[name])
            if info is not None and info.hidden:
                continue
            image = images.get(name)
            has_preview = image is not None and image[0].priority >= owner.priority
            if has_preview and image is not None:
                previews[name] = (image[0].path, image[1], image[2])
            entries[name] = MapEntry(
                name=name,
                title=(info.title if info and info.title else name),
                description=info.description if info else "",
                author=info.author if info else "",
                gametypes=info.gametypes if info else (),
                has_mapinfo=info is not None,
                preview=has_preview,
                source=owner.origin,
            )
        self._entries = dict(sorted(entries.items()))
        self._previews = previews

    @staticmethod
    def _read_generated(path: Path) -> _MapInfo | None:
        try:
            if path.stat().st_size > _MAX_MAPINFO_BYTES:
                return None
            return parse_mapinfo(path.read_text(errors="replace"))
        except OSError as exc:
            log.warning("cannot read %s: %s", path, exc)
            return None

    @staticmethod
    def _read_mapinfo(src: _Source, member: str) -> _MapInfo | None:
        try:
            with zipfile.ZipFile(src.path) as zf:
                if zf.getinfo(member).file_size > _MAX_MAPINFO_BYTES:
                    return None
                return parse_mapinfo(zf.read(member).decode("utf-8", errors="replace"))
        except (OSError, KeyError, zipfile.BadZipFile) as exc:
            log.warning("cannot read %s in %s: %s", member, src.path, exc)
            return None

    # -- queries -------------------------------------------------------------------------
    def maps(self) -> list[MapEntry]:
        self._refresh()
        return list(self._entries.values())

    def get(self, name: str) -> MapEntry | None:
        self._refresh()
        return self._entries.get(name)

    def gametype_map(self) -> dict[str, frozenset[str]]:
        """Map name -> the gametypes it supports (empty when unknown)."""
        return {e.name: frozenset(e.gametypes) for e in self.maps()}

    def gametypes_available(self) -> set[str]:
        """The gametypes at least one installed map supports."""
        available: set[str] = set()
        for entry in self.maps():
            available.update(entry.gametypes)
        return available

    def preview(self, name: str) -> tuple[bytes, str] | None:
        """The preview image bytes and media type, or ``None`` when the map has none."""
        self._refresh()
        found = self._previews.get(name)
        if found is None:
            return None
        path, member, media_type = found
        try:
            with zipfile.ZipFile(path) as zf:
                if zf.getinfo(member).file_size > _MAX_PREVIEW_BYTES:
                    return None
                return zf.read(member), media_type
        except (OSError, KeyError, zipfile.BadZipFile) as exc:
            log.warning("cannot read preview %s in %s: %s", member, path, exc)
            return None
